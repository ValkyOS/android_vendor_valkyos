#!/usr/bin/env python3
# ValkyOS: generate string overlays that replace "LineageOS" (and the short
# form "Lineage", as in "Lineage Recovery") with "ValkyOS" in every language
# of an app.
# Every <string> that contains "Lineage" is copied with the new name,
# except the names given in SKIP (exact names, or prefixes ending in "*").
# Usage: python3 hacer-textos-valkyos.py <app res dir> <overlay res dir> [SKIP,SKIP,...]
import os
import re
import sys

STRING_RE = re.compile(r'<string\s+name="([^"]+)"[^>]*>.*?</string>', re.S)
NAME_RE = re.compile(r'Lineage(?:OS)?')

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!--\n'
          '     SPDX-FileCopyrightText: The LineageOS Project\n'
          '     SPDX-FileCopyrightText: 2026 The ValkyOS Project\n'
          '     SPDX-License-Identifier: Apache-2.0\n'
          '-->\n'
          '<!-- Generated by hacer-textos-valkyos.py: LineageOS -> ValkyOS. -->\n'
          '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2">\n')


def skipped(name, skip):
    for s in skip:
        if s.endswith("*") and name.startswith(s[:-1]):
            return True
        if name == s:
            return True
    return False


def main():
    src, dst = sys.argv[1], sys.argv[2]
    skip = [s for s in (sys.argv[3].split(",") if len(sys.argv) > 3 else []) if s]
    total = 0
    for d in sorted(os.listdir(src)):
        f = os.path.join(src, d, "strings.xml")
        if not d.startswith("values") or not os.path.isfile(f):
            continue
        text = open(f, encoding="utf-8").read()
        out = []
        for m in STRING_RE.finditer(text):
            if skipped(m.group(1), skip) or "Lineage" not in m.group(0):
                continue
            out.append("    " + NAME_RE.sub("ValkyOS", m.group(0)))
        if not out:
            continue
        os.makedirs(os.path.join(dst, d), exist_ok=True)
        with open(os.path.join(dst, d, "strings.xml"), "w", encoding="utf-8") as o:
            o.write(HEADER + "\n".join(out) + "\n</resources>\n")
        total += len(out)
    print("TOTAL", total)


if __name__ == "__main__":
    main()
